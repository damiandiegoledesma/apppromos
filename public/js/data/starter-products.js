function normalizeIdentity(value = "") {
  return String(value || "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function identityOf(product = {}) {
  return `${normalizeIdentity(product.rubro || product.category)}::${normalizeIdentity(product.nombre || product.name)}`;
}

export function createStarterProducts() {
  return STARTER_PRODUCTS.map((product) => ({
    ...product,
    precio: 0,
    precioSugerido: 0,
    active: true,
    activo: true,
    starterCatalogVersion: STARTER_CATALOG_VERSION
  }));
}

export function mergeStarterProducts(currentProducts = []) {
  const current = Array.isArray(currentProducts) ? currentProducts.filter(Boolean) : [];
  const currentByIdentity = new Map(current.map((product) => [identityOf(product), product]));
  const used = new Set();

  const starter = createStarterProducts().map((product) => {
    const identity = identityOf(product);
    const existing = currentByIdentity.get(identity);
    used.add(identity);
    if (!existing) return product;

    return {
      ...product,
      ...existing,
      id: existing.id || existing.productKey || product.id,
      productKey: existing.productKey || existing.id || product.productKey,
      nombre: existing.nombre || existing.name || product.nombre,
      rubro: existing.rubro || existing.category || product.rubro,
      subrubro: existing.subrubro ?? product.subrubro,
      unidad: existing.unidad || product.unidad,
      precio: Number(existing.precio || 0),
      precioSugerido: Number(existing.precioSugerido || 0),
      active: existing.active !== false,
      activo: existing.activo !== false,
      starterCatalogVersion: STARTER_CATALOG_VERSION
    };
  });

  const custom = current.filter((product) => !used.has(identityOf(product)));
  return [...starter, ...custom];
}

export function getStarterProductCount() {
  return STARTER_PRODUCTS.length;
}

